/**
 * The theme compiler: a folder of `.tpl` files in, one JavaScript module out.
 *
 * This is steps 1–5 of the pipeline in docs/TEMPLATE_ENGINE.md, all in one
 * pass: parse every file, resolve `{% render %}` statically, check every
 * expression against the drops, generate the module, and hash it into a
 * version. Nothing about a request touches this code; a request evaluates
 * the module once and then calls into it.
 *
 * The module is content-addressed by `version`, so two versions can live
 * side by side and a rollback is a pointer change. The manifest is what the
 * platform stores beside it: which routes and sections exist, which drops
 * each reads, and how much of the markup was hoisted.
 */

import type { SectionSchema } from '../model/sections'
import type { ParsedTemplate, TemplateNode } from './ast'
import { rendersOf } from './ast'
import { checkTemplate, type SnippetInfo } from './check'
import { createHoistCollector, generateUnit } from './codegen'
import type { Diagnostic } from './diagnostics'
import { error, formatDiagnostic, hasErrors, warning } from './diagnostics'
import type { TemplateRoute, TemplateScope } from './drops'
import { parseTemplate } from './parse'
import type { TemplateRuntime, ThemeModule } from './runtime'
import { evaluateThemeModule } from './runtime'
import { compileSectionSchema } from './schema'

/** The templates a theme may provide, and the files that name each one. */
export const ROUTE_FILES: Record<TemplateRoute, readonly string[]> = {
  home: ['templates/index.tpl', 'templates/home.tpl'],
  product: ['templates/product.tpl'],
  article: ['templates/article.tpl'],
  catalog: ['templates/catalog.tpl', 'templates/collection.tpl'],
  orderTracking: ['templates/order-tracking.tpl', 'templates/order_tracking.tpl'],
}

export const TEMPLATE_ROUTES = Object.keys(ROUTE_FILES) as TemplateRoute[]

export const LAYOUT_FILE = 'layout/theme.tpl'
export const SECTIONS_PREFIX = 'sections/'
export const SNIPPETS_PREFIX = 'snippets/'
export const ASSETS_PREFIX = 'assets/'

/** Bounds on an untrusted theme, so a publish cannot run away with a server. */
export interface ThemeLimits {
  maxFiles: number
  maxFileBytes: number
  maxTotalBytes: number
  /** The most `{% render %}` sites in the whole theme. */
  maxIncludes: number
}

export const DEFAULT_THEME_LIMITS: ThemeLimits = {
  maxFiles: 200,
  maxFileBytes: 128_000,
  maxTotalBytes: 1_000_000,
  maxIncludes: 500,
}

export interface ThemeFiles {
  readonly [path: string]: string
}

export interface UnitManifest {
  /** Root drops the unit reads, snippets included. */
  uses: string[]
}

export interface SectionManifest extends UnitManifest {
  schema: SectionSchema | null
}

export interface ThemeManifest {
  version: string
  routes: Partial<Record<TemplateRoute, UnitManifest>>
  sections: Record<string, SectionManifest>
  snippets: string[]
  layout: boolean
  assets: string[]
  hoisted: number
  /** Every drop the theme reads, unioned — the loader's one-batch prefetch list. */
  uses: string[]
}

export interface CompiledTheme {
  /** Content hash of the emitted module plus the theme's assets. */
  version: string
  /** The generated module. Evaluate it with `activateTheme`. */
  source: string
  manifest: ThemeManifest
  diagnostics: Diagnostic[]
}

/**
 * Compiles a theme. Always returns — a theme with errors still reports every
 * error it found, and `hasErrors` is how a caller decides whether it may be
 * activated.
 */
export function compileTheme(
  files: ThemeFiles,
  options: { limits?: Partial<ThemeLimits> } = {},
): CompiledTheme {
  const limits = { ...DEFAULT_THEME_LIMITS, ...options.limits }
  const diagnostics: Diagnostic[] = []

  const normalized = normalizeFiles(files, limits, diagnostics)
  if (hasErrors(diagnostics)) {
    return { version: '', source: '', manifest: emptyManifest(), diagnostics }
  }

  const parsed = parseUnits(normalized, diagnostics)
  const snippetInfo = collectSnippetInfo(parsed, diagnostics, limits)
  const hoists = createHoistCollector()
  const functionNames = createFunctionNames(parsed)

  const lines: string[] = []
  lines.push('/* Generated by the Pesanle template compiler. Do not edit. */')
  lines.push('"use strict";')
  lines.push('var __h = __rt.h, __f = __rt.filters, __style = __rt.style;')

  /* Snippets: each one is a function of (scope, args). */
  const snippetUses = new Map<string, string[]>()
  const snippetRenders = new Map<string, string[]>()
  for (const snippet of parsed.snippets.values()) {
    const info = snippetInfo.get(snippet.name)!
    const result = checkTemplate(snippet.ast.nodes, {
      file: snippet.path,
      snippetArgs: info.args,
      resolveSnippet: (name) => snippetInfo.get(name) ?? null,
    })
    diagnostics.push(...result.diagnostics)
    snippetUses.set(snippet.name, result.uses)
    snippetRenders.set(snippet.name, result.renders)
    const generated = generateUnit(
      snippet.ast.nodes,
      { args: info.args, snippetFunctions: functionNames.snippets },
      hoists,
    )
    lines.push(`function ${functionNames.snippets.get(snippet.name)!}(__scope, __args) {`)
    lines.push(generated.body)
    lines.push('}')
  }

  /* Sections: each one is a function of (scope), with its schema compiled. */
  const sectionManifests: Record<string, SectionManifest> = {}
  const sectionUses = new Map<string, string[]>()
  const sectionRenders = new Map<string, string[]>()
  for (const section of parsed.sections.values()) {
    const schema = compileSectionSchema(section.ast.schema, {
      type: section.name,
      file: section.path,
    })
    diagnostics.push(...schema.diagnostics)
    const result = checkTemplate(section.ast.nodes, {
      file: section.path,
      sectionSettings: schema.compiled?.settingsType,
      resolveSnippet: (name) => snippetInfo.get(name) ?? null,
    })
    diagnostics.push(...result.diagnostics)
    sectionUses.set(section.name, result.uses)
    sectionRenders.set(section.name, result.renders)
    sectionManifests[section.name] = { uses: [], schema: schema.compiled?.schema ?? null }
    const generated = generateUnit(
      section.ast.nodes,
      { snippetFunctions: functionNames.snippets },
      hoists,
    )
    lines.push(`function ${functionNames.sections.get(section.name)!}(__scope) {`)
    lines.push(generated.body)
    lines.push('}')
  }

  /* Routes: a body function, wrapped in the layout when the theme has one. */
  const routeUses = new Map<string, string[]>()
  const routeRenders = new Map<string, string[]>()
  for (const [route, unit] of parsed.routes) {
    const result = checkTemplate(unit.ast.nodes, {
      file: unit.path,
      resolveSnippet: (name) => snippetInfo.get(name) ?? null,
    })
    diagnostics.push(...result.diagnostics)
    routeUses.set(route, result.uses)
    routeRenders.set(route, result.renders)
    const generated = generateUnit(
      unit.ast.nodes,
      { snippetFunctions: functionNames.snippets },
      hoists,
    )
    lines.push(`function ${functionNames.routeBodies.get(route)!}(__scope) {`)
    lines.push(generated.body)
    lines.push('}')
  }

  /* The layout shell, with `content_for_layout` as its body slot. */
  let layoutUses: string[] = []
  let layoutRenders: string[] = []
  if (parsed.layout) {
    const result = checkTemplate(parsed.layout.ast.nodes, {
      file: parsed.layout.path,
      isLayout: true,
      resolveSnippet: (name) => snippetInfo.get(name) ?? null,
    })
    diagnostics.push(...result.diagnostics)
    layoutUses = result.uses
    layoutRenders = result.renders
    const generated = generateUnit(
      parsed.layout.ast.nodes,
      { isLayout: true, snippetFunctions: functionNames.snippets },
      hoists,
    )
    lines.push(`function ${functionNames.layout}(__scope, __body) {`)
    lines.push(generated.body)
    lines.push('}')
  }

  lines.push(...hoists.lines)

  const routeEntries: string[] = []
  for (const [route, unit] of parsed.routes) {
    const body = functionNames.routeBodies.get(route)!
    if (parsed.layout) {
      const wrapper = functionNames.routes.get(route)!
      lines.push(
        `function ${wrapper}(__scope) { return ${functionNames.layout}(__scope, ${body}); }`,
      )
      routeEntries.push(`${routeKey(route)}: ${wrapper}`)
    } else {
      routeEntries.push(`${routeKey(route)}: ${body}`)
    }
  }

  const sectionEntries = [...parsed.sections.values()].map(
    (section) => `${JSON.stringify(section.name)}: ${functionNames.sections.get(section.name)!}`,
  )
  lines.push(
    `return { routes: { ${routeEntries.join(', ')} }, sections: { ${sectionEntries.join(', ')} }, layout: ${parsed.layout ? functionNames.layout : 'null'} };`,
  )

  const source = lines.join('\n')
  const assets = Object.keys(normalized).filter((path) => path.startsWith(ASSETS_PREFIX))
  const assetsHash = contentHash(
    assets.map((path) => `${path}:${normalized[path] ?? ''}`).join('\n'),
  )
  const version = contentHash(`${source}\n/* assets ${assetsHash} */`)

  const uses = new Set<string>()
  const resolveUses = (own: string[], renders: string[], seen = new Set<string>()): string[] => {
    const out = new Set(own)
    for (const snippet of renders) {
      if (seen.has(snippet)) continue
      seen.add(snippet)
      for (const name of resolveUses(
        snippetUses.get(snippet) ?? [],
        snippetRenders.get(snippet) ?? [],
        seen,
      )) {
        out.add(name)
      }
    }
    return [...out]
  }

  for (const [route, own] of routeUses) {
    // A route is drawn inside the layout, so the layout's drops belong to
    // every route's prefetch list.
    const resolved = resolveUses(
      [...own, ...layoutUses],
      [...(routeRenders.get(route) ?? []), ...layoutRenders],
    )
    routeUses.set(route, resolved)
    for (const name of resolved) uses.add(name)
  }
  for (const [name, own] of sectionUses) {
    const resolved = resolveUses(own, sectionRenders.get(name) ?? [])
    sectionUses.set(name, resolved)
    sectionManifests[name]!.uses = resolved
    for (const drop of resolved) uses.add(drop)
  }

  const manifest: ThemeManifest = {
    version,
    routes: Object.fromEntries(
      [...routeUses].map(([route, unitUses]) => [route, { uses: unitUses }]),
    ) as ThemeManifest['routes'],
    sections: sectionManifests,
    snippets: [...parsed.snippets.keys()],
    layout: Boolean(parsed.layout),
    assets,
    hoisted: hoists.count,
    uses: [...uses],
  }

  return { version, source, manifest, diagnostics }
}

