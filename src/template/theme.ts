/* Activation                                                                 */
/* -------------------------------------------------------------------------- */

export interface ActivatedTheme {
  version: string
  manifest: ThemeManifest
  diagnostics: Diagnostic[]
  /** Draws a route, or `null` when the theme does not provide that template. */
  renderRoute(route: TemplateRoute, scope: TemplateScope): unknown
  /** Draws a compiled section, or `null` when the theme does not provide it. */
  renderSection(type: string, scope: TemplateScope): unknown
}

/**
 * Evaluates a compiled theme against a runtime, once per theme version.
 *
 * The compiled source is generated code, loaded server-side only — never
 * fetched into a shopper's browser (see docs/TEMPLATE_ENGINE.md, "Security").
 */
export function activateTheme(theme: CompiledTheme, runtime: TemplateRuntime): ActivatedTheme {
  if (hasErrors(theme.diagnostics)) {
    throw new Error(
      `Cannot activate a theme with compile errors:\n${theme.diagnostics
        .filter((diagnostic) => diagnostic.severity === 'error')
        .map(formatDiagnostic)
        .join('\n')}`,
    )
  }
  const module: ThemeModule = evaluateThemeModule(theme.source, runtime)
  return {
    version: theme.version,
    manifest: theme.manifest,
    diagnostics: theme.diagnostics,
    renderRoute: (route, scope) => module.routes[route]?.(scope) ?? null,
    renderSection: (type, scope) => module.sections[type]?.(scope) ?? null,
  }
}

/** Compile and activate in one call, for a host that has the runtime ready. */
export function createTheme(
  files: ThemeFiles,
  runtime: TemplateRuntime,
  options: { limits?: Partial<ThemeLimits> } = {},
): ActivatedTheme {
  return activateTheme(compileTheme(files, options), runtime)
}

