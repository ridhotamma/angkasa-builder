interface ParsedUnit {
  path: string
  name: string
  ast: ParsedTemplate
}

interface ParsedTheme {
  layout: ParsedUnit | null
  routes: Map<TemplateRoute, ParsedUnit>
  sections: Map<string, ParsedUnit>
  snippets: Map<string, ParsedUnit>
}

function normalizeFiles(
  files: ThemeFiles,
  limits: ThemeLimits,
  diagnostics: Diagnostic[],
): Record<string, string> {
  const normalized: Record<string, string> = {}
  let total = 0
  let count = 0
  for (const [rawPath, contents] of Object.entries(files)) {
    const path = rawPath.replace(/\\/g, '/').replace(/^\.?\//, '')
    if (!path || path.split('/').includes('..')) {
      diagnostics.push(error('invalid-section-file', `Invalid theme path "${rawPath}".`))
      continue
    }
    count++
    if (count > limits.maxFiles) {
      diagnostics.push(
        error('too-many-files', `A theme may hold at most ${limits.maxFiles} files.`),
      )
      break
    }
    const bytes = contents.length
    if (bytes > limits.maxFileBytes) {
      diagnostics.push(
        error(
          'file-too-large',
          `"${path}" is ${bytes} bytes; the cap is ${limits.maxFileBytes}.`,
          path,
        ),
      )
      continue
    }
    total += bytes
    if (total > limits.maxTotalBytes) {
      diagnostics.push(error('theme-too-large', `The theme is over ${limits.maxTotalBytes} bytes.`))
      break
    }
    normalized[path] = contents
  }
  return normalized
}

function parseUnits(files: Record<string, string>, diagnostics: Diagnostic[]): ParsedTheme {
  const theme: ParsedTheme = {
    layout: null,
    routes: new Map(),
    sections: new Map(),
    snippets: new Map(),
  }

  for (const [path, contents] of Object.entries(files)) {
    if (path === LAYOUT_FILE) {
      theme.layout = unit(path, 'layout', contents, diagnostics)
      continue
    }
    if (path.startsWith(SECTIONS_PREFIX) && path.endsWith('.tpl')) {
      const name = path.slice(SECTIONS_PREFIX.length, -'.tpl'.length)
      if (!/^[a-z][a-z0-9-]*$/.test(name)) {
        diagnostics.push(
          error(
            'invalid-section-file',
            `Section files are named lower-kebab-case; "${name}" is not.`,
            path,
          ),
        )
        continue
      }
      theme.sections.set(name, unit(path, name, contents, diagnostics))
      continue
    }
    if (path.startsWith(SNIPPETS_PREFIX) && path.endsWith('.tpl')) {
      const name = path.slice(SNIPPETS_PREFIX.length, -'.tpl'.length)
      if (!/^[a-z][a-z0-9-]*$/.test(name)) {
        diagnostics.push(
          error(
            'invalid-section-file',
            `Snippet files are named lower-kebab-case; "${name}" is not.`,
            path,
          ),
        )
        continue
      }
      theme.snippets.set(name, unit(path, name, contents, diagnostics))
      continue
    }
    if (path.startsWith(ASSETS_PREFIX)) continue
  }

  for (const [route, candidates] of Object.entries(ROUTE_FILES) as Array<
    [TemplateRoute, readonly string[]]
  >) {
    const path = candidates.find((candidate) => candidate in files)
    if (!path) {
      // A theme may design only some pages; the host falls back to its own
      // template for the rest. Worth saying out loud, not worth refusing.
      diagnostics.push(
        warning(
          'missing-route-template',
          `No template for "${route}" (expected ${candidates[0]}); the host's own will be used.`,
        ),
      )
      continue
    }
    theme.routes.set(route, unit(path, route, files[path]!, diagnostics))
  }

  return theme
}

function unit(path: string, name: string, contents: string, diagnostics: Diagnostic[]): ParsedUnit {
  const ast = parseTemplate(contents, { file: path })
  diagnostics.push(...ast.diagnostics)
  return { path, name, ast }
}

/**
 * Every snippet's argument names: the union across its call sites, which is
 * how a snippet is parameterised in a compiled theme. Walking every unit once
 * also counts include sites, so an absurd theme is refused before codegen.
 */
function collectSnippetInfo(
  parsed: ParsedTheme,
  diagnostics: Diagnostic[],
  limits: ThemeLimits,
): Map<string, SnippetInfo> {
  const info = new Map<string, { args: Set<string> }>()
  for (const name of parsed.snippets.keys()) info.set(name, { args: new Set() })

  let includes = 0
  const walk = (path: string, nodes: readonly TemplateNode[]) => {
    for (const render of rendersOf(nodes)) {
      includes++
      if (includes > limits.maxIncludes) {
        diagnostics.push(
          error('too-many-includes', `A theme may render at most ${limits.maxIncludes} snippets.`),
        )
        return
      }
      const entry = info.get(render.snippet)
      if (!entry) {
        // The checker reports the missing snippet with its own location; here
        // it only stops the argument collection.
        continue
      }
      for (const argument of render.args) entry.args.add(argument.name)
    }
  }

  const units = [
    ...parsed.routes.values(),
    ...parsed.sections.values(),
    ...parsed.snippets.values(),
    ...(parsed.layout ? [parsed.layout] : []),
  ]
  for (const unit of units) walk(unit.path, unit.ast.nodes)

  return new Map(
    [...info].map(([name, entry]) => [
      name,
      { args: [...entry.args].sort() } satisfies SnippetInfo,
    ]),
  )
}

interface FunctionNames {
  snippets: Map<string, string>
  sections: Map<string, string>
  routeBodies: Map<TemplateRoute, string>
  routes: Map<TemplateRoute, string>
  layout: string
}

/** Generated names are sanitised and de-duplicated, so two files can never collide. */
function createFunctionNames(parsed: ParsedTheme): FunctionNames {
  const used = new Set<string>()
  const unique = (hint: string): string => {
    let name = hint.replace(/[^a-zA-Z0-9_$]/g, '_')
    if (!/^[a-zA-Z_$]/.test(name)) name = `_${name}`
    let candidate = name
    let suffix = 2
    while (used.has(candidate)) candidate = `${name}_${suffix++}`
    used.add(candidate)
    return candidate
  }

  const snippets = new Map<string, string>()
  for (const name of parsed.snippets.keys()) snippets.set(name, unique(`__snip_${name}`))
  const sections = new Map<string, string>()
  for (const name of parsed.sections.keys()) sections.set(name, unique(`__sec_${name}`))
  const routeBodies = new Map<TemplateRoute, string>()
  for (const route of parsed.routes.keys()) routeBodies.set(route, unique(`__body_${route}`))
  const routes = new Map<TemplateRoute, string>()
  for (const route of parsed.routes.keys()) routes.set(route, unique(`__route_${route}`))
  return { snippets, sections, routeBodies, routes, layout: unique('__layout') }
}

function routeKey(route: string): string {
  return /^[a-zA-Z_$][\w$]*$/.test(route) ? route : JSON.stringify(route)
}

function emptyManifest(): ThemeManifest {
  return {
    version: '',
    routes: {},
    sections: {},
    snippets: [],
    layout: false,
    assets: [],
    hoisted: 0,
    uses: [],
  }
}

/**
 * A deterministic 64-bit FNV-1a hash of a string, as 16 hex digits. The
 * version an artifact is addressed by — never a security boundary, only a
 * cache key and an identity.
 */
export function contentHash(source: string): string {
  let hash = 0xcbf29ce484222325n
  const prime = 0x100000001b3n
  const mask = 0xffffffffffffffffn
  for (let i = 0; i < source.length; i++) {
    hash = ((hash ^ BigInt(source.charCodeAt(i))) * prime) & mask
  }
  return hash.toString(16).padStart(16, '0')
}
