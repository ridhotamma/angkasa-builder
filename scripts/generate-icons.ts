/**
 * Generate the page builder's icon glyphs from the catalogue.
 *
 * `react-icons/lu` ships every Lucide icon in one ~800 KB module, and Rollup
 * cannot split exports out of a single module — importing it anywhere drags the
 * whole set into one chunk. So each glyph is vendored here into its own
 * self-contained module (its SVG markup inlined), which the bundler *can* split
 * into a chunk of its own. Alongside them this writes the maps that read them:
 * the storefront's eager core and lazy loaders, and the editor's full static
 * map for the picker.
 *
 * Run: `bun run generate:icons` from `packages/page-builder`. The output is
 * committed; re-run when `ICON_MANIFEST` or `CORE_ICON_NAMES` changes.
 */

import { createElement, type FunctionComponent } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import * as Lu from 'react-icons/lu'

import { CORE_ICON_NAMES, ICON_MANIFEST, type IconName } from '../src/model/icons'

const ROOT = new URL('../src/', import.meta.url)
const BANNER = '// Generated by scripts/generate-icons.ts. Do not edit by hand.\n'

/** A name as a JS identifier: `shield-check` -> `iconShieldCheck`. */
function ident(name: string): string {
  const pascal = name
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
  return `icon${pascal}`
}

/** A name as an object key: quoted only when it needs to be. */
function key(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : `'${name}'`
}

/** One shape inside an icon's SVG. */
interface GlyphChild {
  tag: string
  attrs: Array<[string, string]>
}

/** The shapes react-icons draws for one icon, read from its own markup. */
function svgChildren(component: string): GlyphChild[] {
  const Icon = (Lu as unknown as Record<string, FunctionComponent>)[component]
  if (typeof Icon !== 'function') throw new Error(`react-icons/lu has no ${component}`)
  const markup = renderToStaticMarkup(createElement(Icon, {}))
  const inner = markup.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
  const children: GlyphChild[] = []
  for (const match of inner.matchAll(/<([a-zA-Z]+)([^>]*?)\s*\/?>(?:<\/\1>)?/g)) {
    const attrs: Array<[string, string]> = []
    for (const attr of match[2]!.matchAll(/([a-zA-Z][a-zA-Z0-9-]*)="([^"]*)"/g)) {
      attrs.push([attr[1]!, attr[2]!])
    }
    children.push({ tag: match[1]!, attrs })
  }
  return children
}

/** A self-contained module for one glyph: its shapes inlined, no react-icons. */
function glyphModule(component: string, children: GlyphChild[]): string {
  const shapes = children
    .map(({ tag, attrs }) => {
      const props = attrs.map(
        ([name, value]) => `${JSON.stringify(name)}: ${JSON.stringify(value)}`,
      )
      return `    createElement(${JSON.stringify(tag)}, { ${props.join(', ')} }),`
    })
    .join('\n')
  return `${BANNER}
import { createElement, type SVGProps } from 'react'

/** The \`${component}\` glyph, vendored from react-icons/lu so it splits alone. */
// prettier-ignore
export default function Glyph(props: SVGProps<SVGSVGElement>) {
  return createElement(
    'svg',
    {
      xmlns: 'http://www.w3.org/2000/svg',
      width: '1em',
      height: '1em',
      viewBox: '0 0 24 24',
      fill: 'none',
      stroke: 'currentColor',
      strokeWidth: 2,
      strokeLinecap: 'round',
      strokeLinejoin: 'round',
      ...props,
    },
${shapes}
  )
}
`
}

async function write(path: string, contents: string): Promise<void> {
  await Bun.write(new URL(path, ROOT), contents)
}

async function main(): Promise<void> {
  const names = Object.keys(ICON_MANIFEST) as IconName[]

  // One self-contained module per icon, so each is its own lazy chunk.
  for (const name of names) {
    const component = ICON_MANIFEST[name]
    await write(`render/glyphs/${name}.ts`, glyphModule(component, svgChildren(component)))
  }

  // The storefront's lazy loaders.
  const loaders = names
    .map((name) => `  ${key(name)}: () => import('./glyphs/${name}'),`)
    .join('\n')
  await write(
    'render/icon-loaders.ts',
    `${BANNER}
import type { GlyphComponent } from './glyph'
import type { IconName } from '../model/icons'

/**
 * One loader per icon, so the bundler can split each glyph into its own chunk.
 * \`render/icons\` draws a core glyph directly and lazily pulls the rest, so the
 * storefront ships only the icons a page actually renders.
 */
// prettier-ignore
export const ICON_LOADERS: Record<IconName, () => Promise<{ default: GlyphComponent }>> = {
${loaders}
}
`,
  )

  // The storefront's eager core.
  const coreImports = CORE_ICON_NAMES.map(
    (name) => `import ${ident(name)} from './glyphs/${name}'`,
  ).join('\n')
  const coreEntries = CORE_ICON_NAMES.map((name) => `  ${key(name)}: ${ident(name)},`).join('\n')
  await write(
    'render/core-icons.ts',
    `${BANNER}
import type { GlyphComponent } from './glyph'
import type { IconName } from '../model/icons'
${coreImports}

/**
 * The glyphs the storefront ships eagerly, so the icons a page is most likely
 * to show above the fold paint in the first HTML rather than stream in. Every
 * other name is a lazy chunk; see \`render/icons\`.
 */
// prettier-ignore
export const CORE_ICONS: Partial<Record<IconName, GlyphComponent>> = {
${coreEntries}
}
`,
  )

  // The editor's full static map, for the picker.
  const allImports = names
    .map((name) => `import ${ident(name)} from '../render/glyphs/${name}'`)
    .join('\n')
  const allEntries = names.map((name) => `  ${key(name)}: ${ident(name)},`).join('\n')
  await write(
    'editor/icon-glyphs.ts',
    `${BANNER}
import type { GlyphComponent } from '../render/glyph'
import type { IconName } from '../model/icons'
${allImports}

/**
 * Every glyph, statically, for the editor's picker — the admin bundle can carry
 * them all. Storefront code must not import this; it uses \`render/icons\`.
 */
// prettier-ignore
export const ICON_GLYPHS: Record<IconName, GlyphComponent> = {
${allEntries}
}
`,
  )

  console.log(
    `[generate-icons] wrote ${names.length} glyphs (${CORE_ICON_NAMES.length} eager core)`,
  )
}

await main()
